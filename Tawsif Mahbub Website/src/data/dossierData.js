// Helper to generate URL-safe slugs for works
export function getWorkSlug(work) {
  if (!work) return '';
  if (work.slug) return work.slug;
  const englishPart = work.title.split('(')[0].trim();
  const slug = englishPart
    .toLowerCase()
    .replace(/@/g, 'at-')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return slug || `work-${work.id}`;
}


